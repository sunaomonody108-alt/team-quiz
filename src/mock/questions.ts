import type { QuestionInput } from '../lib/types'

/**
 * 動作確認用のモック問題(本番の20問ではありません)。
 * 本番問題は管理画面の「問題の一括登録」で同じ形式のJSONを貼り付けて差し替えます。
 */
const mc = (
  position: number,
  prompt: string,
  labels: [string, string, string, string],
  correctIndex: number,
  explanation: string,
): QuestionInput => ({
  position,
  type: 'multiple_choice',
  prompt,
  choices: labels.map((label, i) => ({ id: 'abcd'[i], label })),
  correctChoiceId: 'abcd'[correctIndex],
  explanation,
})

const ord = (position: number, prompt: string, correctLabels: string[], shownOrder: number[], explanation: string): QuestionInput => {
  const ids = correctLabels.map((_, i) => `o${i + 1}`)
  return {
    position,
    type: 'ordering',
    prompt,
    // 表示順(初期並び)は shownOrder の順。正解は ids の順
    choices: shownOrder.map((i) => ({ id: ids[i], label: correctLabels[i] })),
    correctOrderIds: ids,
    explanation,
  }
}

